readme = """# Nesta Backend

Nesta Backend is a Spring Boot application providing the core logic, APIs, and generation engine for the Nesta platform.

## Getting Started

1. Ensure Java 21 is installed.
2. Ensure you have a database connection (configured in `application.properties`).
3. Run the application: `./mvnw spring-boot:run`

## Project Structure
- `src/main/java/com/nesta/`
  - `controller/`: REST APIs
  - `service/`: Business logic, Template Resolver, Generation Engine
  - `entity/`: JPA entities
  - `repository/`: Spring Data JPA repositories
  - `security/`: JWT authentication and security configurations
  - `config/`: Application configurations (e.g., AsyncConfig)
  - `dto/`: Data Transfer Objects
  - `bootstrap/`: Application data seeders
"""

api_doc = """# API Documentation

## Authentication
- `POST /api/auth/register`: Register a new user
- `POST /api/auth/login`: Login and receive JWT
- `POST /api/auth/refresh`: Refresh an existing JWT

## Technologies & Registry
- `GET /api/technologies/frontend`: Get all frontend frameworks
- `GET /api/technologies/backend`: Get all backend frameworks
- `GET /api/technologies/database`: Get all databases
- `GET /api/features`: Get all available features
- `GET /api/templates`: Get all UI templates

## Projects
- `POST /api/projects`: Create a new project configuration
- `POST /api/projects/{id}/generate`: Trigger async generation job
- `GET /api/projects/{id}/artifacts`: Get all generated artifacts
"""

arch_doc = """# Architecture Overview

## Components
1. **API Layer**: Exposes REST endpoints for client interaction. Protected via JWT.
2. **Service Layer**: Handles business logic, including registry lookups and project configuration validation.
3. **Validation Component**: The `CompatibilityValidator` ensures projects generated in Ultimate mode have valid tech stacks, while Simple mode strictly validates UI template inputs.
4. **Generation Engine**: The `ProjectGenerator` handles heavy I/O operations asynchronously using Spring `@Async`.
5. **Template System**: The `TemplateResolver` dynamically locates and resolves templates based on project mode configuration.

## Async Generation Workflow
1. Client requests project generation.
2. A `GenerationJob` is created and its ID is returned to the client immediately.
3. Background thread reads templates, parses variables (`{{PROJECT_NAME}}`, etc.), and creates artifacts.
4. Client polls or uses websockets to check job completion and retrieve artifacts.
"""

tpl_doc = """# Template Development Guide

Nesta's generation engine supports two modes: Simple and Ultimate.

## Adding a Simple Template
1. Create a new directory in `templates/simple/<template-name>`.
2. Add all necessary scaffold files.
3. Use moustache-like variables in the files (e.g., `{{PROJECT_NAME}}`).
4. Add the template entry in the `DataSeeder` or DB registry.

## Adding an Ultimate Template Segment
1. Create a segment directory in `templates/ultimate/<technology-name>`.
2. Ensure variable mappings for features (e.g., `{{FEATURES_LIST}}`) exist.
3. Update the `TemplateResolver` logic to merge these template segments correctly based on `CompatibilityValidator` outputs.
"""

