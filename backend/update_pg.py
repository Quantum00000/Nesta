content = content.replace('getPackageJson(safeName)', 'getPackageJson(safeName, projectDesc)')
content = content.replace('private String getPomXml(String name) {', 'private String getPomXml(String name, String desc) {')
content = content.replace('private String getPackageJson(String name) {', 'private String getPackageJson(String name, String desc) {')

content = content.replace('"    <name>" + name + "</name>\\n" +', '"    <name>" + name + "</name>\\n" +\n               "    <description>" + desc + "</description>\\n" +')
content = content.replace('"  \\"name\\": \\"" + name + "\\",\\n" +', '"  \\"name\\": \\"" + name + "\\",\\n" +\n               "  \\"description\\": \\"" + desc + "\\",\\n" +')

with open('src/main/java/com/nesta/service/ProjectGenerator.java', 'w', encoding='utf-8') as f:
    f.write(content)
