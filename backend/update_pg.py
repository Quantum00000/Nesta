import re

with open('src/main/java/com/nesta/service/ProjectGenerator.java', 'r', encoding='utf-8') as f:
    content = f.read()

content = content.replace('String projectName = job.getProject().getName();', 'String projectName = job.getProject().getName();\n            String projectDesc = job.getProject().getDescription();\n            if (projectDesc == null || projectDesc.isEmpty()) projectDesc = "Generated by Nesta";')
